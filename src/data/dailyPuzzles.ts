/**
 * Get daily puzzle for a specific date (deterministic by day of year)
 */
export function getDailyPuzzleForDate(date: Date = new Date()): Puzzle {
  const startOfYear = new Date(date.getFullYear(), 0, 1);
  const diffDays = Math.floor((date.getTime() - startOfYear.getTime()) / (1000 * 60 * 60 * 24));
  const puzzleIndex = Math.abs(diffDays) % CURATED_PUZZLES.length;
  const basePuzzle = CURATED_PUZZLES[puzzleIndex];

  return {
    ...basePuzzle,
    dayNumber: diffDays + 1,
    dateStr: date.toISOString().split('T')[0]
  };
}
